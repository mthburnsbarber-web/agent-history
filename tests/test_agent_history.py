class TestRedaction(unittest.TestCase):
    def test_patterns(self):
        sys.path.insert(0, str(ROOT))
        from agent_history import redact
        cases = [
            "token sk-proj-abcdefghijklmnopqrstuvwx",
            "Authorization: Bearer abcdefghijklmnopqrstuvwxyz123456",
            "export STRIPE=sk_live_abcdefghijklmnop",
            "https://bucket.s3.amazonaws.com/a.zip?X-Amz-Signature=abc123def456",
            "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXktdjE\n-----END OPENSSH PRIVATE KEY-----",
            '{"api_key": "abcd1234efgh"}',
            "xoxb-1234567890-abcdefghij",
        ]
        for c in cases:
            self.assertIn("[REDACTED", redact(c), c)
        for keep in ("disk-75335039-20", "the task-runner", "skip-this", "eyJ"):
            self.assertEqual(redact(keep), keep)


