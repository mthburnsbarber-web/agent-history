class Fixture(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="agent history "))
        self.home = self.tmp / "home"
        self.claude = self.home / ".claude"
        self.codex = self.home / ".codex"
        self.store = self.tmp / "store"
        proj = self.claude / "projects" / "-work-shop"
        proj.mkdir(parents=True)
        self.claude_file = proj / f"{CLAUDE_SESSION}.jsonl"
        self.claude_file.write_text(jl(*claude_rows()))
        sub = proj / CLAUDE_SESSION / "subagents"
        sub.mkdir(parents=True)
        (sub / "agent-a1.jsonl").write_text(jl({
            "type": "user", "sessionId": CLAUDE_SESSION, "isSidechain": True, "cwd": "/work/shop", "timestamp": "2026-09-01T10:00:06.000Z",
            "message": {"role": "user", "content": "Search the repository for every onClick handler"}}))
        (self.claude / "history.jsonl").write_text(jl(
            {"display": "deploy the shop to staging", "pastedContents": {}, "timestamp": 1756720000000, "project": "/work/shop", "sessionId": "0ld5e551-0000-0000-0000-00000000dead"}))
        day = self.codex / "sessions" / "2026" / "09" / "02"
        day.mkdir(parents=True)
        self.codex_file = day / f"rollout-2026-09-02T08-00-00-{CODEX_SESSION}.jsonl"
        self.codex_file.write_text(jl(*codex_rows()))
        (self.codex / "history.jsonl").write_text(jl({"session_id": CODEX_SESSION, "ts": 1756800001, "text": "Why is the rate limiter returning 429 for every request?"}))
        self.env = dict(os.environ, HOME=str(self.home), AGENT_HISTORY_HOME=str(self.store),
                        CLAUDE_CONFIG_DIR=str(self.claude), CODEX_HOME=str(self.codex), NO_COLOR="1")

    def run_cli(self, *args, check=True):
        r = subprocess.run([sys.executable, str(CLI), *args], env=self.env, capture_output=True, text=True, timeout=120)
        if check and r.returncode != 0:
            self.fail(f"{args} exited {r.returncode}\nstdout:{r.stdout}\nstderr:{r.stderr}")
        return r

    def jsonl(self, *args, check=True):
        r = self.run_cli(*args, "--json", check=check)
        return [json.loads(line) for line in r.stdout.splitlines() if line.strip()]

    def index(self, *extra):
        return json.loads(self.run_cli("index", "--json", *extra).stdout)


class TestAgentHistory(Fixture):
    def test_index_finds_every_source(self):
        report = self.index()
        self.assertEqual(report["files_found"], 5)  # transcript, subagent, two prompt histories, codex rollout
        self.assertEqual(report["indexed"], 5)

    def test_search_claude_and_codex(self):
        self.index()
        hits = self.jsonl("search", "login button")
        self.assertTrue(hits)
        self.assertEqual(hits[0]["session"], CLAUDE_SESSION)
        self.assertEqual(hits[0]["tool"], "claude")
        self.assertEqual(hits[0]["project"], "/work/shop")
        self.assertIn("[login]", hits[0]["excerpt"])
        codex = self.jsonl("search", "rate limiter", "--tool", "codex")
        self.assertEqual({h["session"] for h in codex}, {CODEX_SESSION})

    def test_thinking_reasoning_and_images_are_not_indexed(self):
        self.index()
        for word in ("zebras", "walrus", "iVBORw0KGgo"):
            r = self.run_cli("search", word, check=False)
            self.assertEqual(r.returncode, 1, f"{word} should not be searchable: {r.stdout}")

    def test_secrets_are_redacted_everywhere(self):
        self.index()
        out = self.run_cli("search", "key", "--limit", "50").stdout + self.run_cli("show", CLAUDE_SESSION[:8], "--full").stdout
        self.assertIn("[REDACTED]", out)
        conn = sqlite3.connect(self.store / "history.sqlite")
        bodies = "\n".join(b for (b,) in conn.execute("SELECT body FROM texts"))
        for name, secret in FAKE_SECRETS.items():
            self.assertNotIn(secret, out, name)
            self.assertNotIn(secret, bodies, name)

    def test_raw_snapshot_keeps_exact_bytes(self):
        self.index()
        conn = sqlite3.connect(self.store / "history.sqlite")
        f, sha = conn.execute("SELECT file, sha256 FROM snapshots WHERE path=?", (str(self.claude_file),)).fetchone()
        raw = gzip.open(self.store / "snapshots" / f).read()
        self.assertEqual(raw, self.claude_file.read_bytes())
        self.assertEqual(hashlib.sha256(raw).hexdigest(), sha)

    def test_injected_instructions_are_hidden_by_default(self):
        self.index()
        self.assertEqual(self.run_cli("search", "AGENTS.md", check=False).returncode, 1)
        self.assertTrue(self.jsonl("search", "AGENTS.md", "--all-roles"))
        self.assertEqual(self.run_cli("search", "Caveat", check=False).returncode, 1)

    def test_codex_duplicates_paired_but_real_repeats_kept(self):
        self.index()
        msgs = self.jsonl("show", CODEX_SESSION[:8])
        users = [m["text"] for m in msgs if m["role"] == "user"]
        self.assertEqual(users.count("Why is the rate limiter returning 429 for every request?"), 1)
        self.assertEqual(users.count("continue"), 2)
        assistants = [m["text"] for m in msgs if m["role"] == "assistant"]
        self.assertEqual(assistants, ["The window is in seconds, not milliseconds."])

    def test_tool_calls_and_results_are_searchable(self):
        self.index()
        hits = self.jsonl("search", "window_ms")
        self.assertEqual({h["channel"] for h in hits}, {"tool_use", "tool_result"})
        self.assertTrue(self.jsonl("search", "grep onClick", "--role", "tool"))
        shown = self.run_cli("show", CODEX_SESSION[:8], "--tools").stdout
        self.assertIn("TOOL (tool_use)", shown)
        self.assertNotIn("TOOL", self.run_cli("show", CODEX_SESSION[:8]).stdout)

    def test_sessions_titles_and_prompt_only_sessions(self):
        self.index()
        rows = {r["session"]: r for r in self.jsonl("sessions", "--limit", "10")}
        self.assertEqual(rows[CLAUDE_SESSION]["title"], "Fix the Safari login button")  # not the subagent's prompt
        self.assertEqual(rows[CODEX_SESSION]["title"], "Why is the rate limiter returning 429 for every request?")
        self.assertEqual(rows[CODEX_SESSION]["project"], "/work/api")
        self.assertIn("0ld5e551-0000-0000-0000-00000000dead", rows)  # only the prompt history remembers it
        shown = self.run_cli("show", "0ld5e551").stdout
        self.assertIn("deploy the shop to staging", shown)

    def test_incremental_append_replaces_prefix_snapshot(self):
        self.index()
        again = self.index()
        self.assertEqual(again["indexed"], 0)
        self.assertEqual(again["unchanged"], 5)
        with self.claude_file.open("a") as f:
            f.write(jl({"type": "user", "sessionId": CLAUDE_SESSION, "cwd": "/work/shop", "timestamp": "2026-09-01T11:00:00.000Z",
                        "message": {"role": "user", "content": "Now add a regression test for the Safari tap"}}))
        self.assertEqual(self.index()["indexed"], 1)
        self.assertTrue(self.jsonl("search", "regression test"))
        conn = sqlite3.connect(self.store / "history.sqlite")
        files = conn.execute("SELECT file FROM snapshots WHERE path=?", (str(self.claude_file),)).fetchall()
        self.assertEqual(len(files), 1, "an appended transcript keeps one snapshot")
        prefix = self.claude_file.name[:0] + hashlib.sha256(str(self.claude_file).encode()).hexdigest()[:16]
        self.assertEqual(len(list((self.store / "snapshots").glob(prefix + "-*"))), 1)

    def test_rewritten_transcript_keeps_both_versions(self):
        self.index()
        self.claude_file.write_text(jl(*claude_rows()[:2]))  # shorter, not an append
        self.index()
        conn = sqlite3.connect(self.store / "history.sqlite")
        self.assertEqual(conn.execute("SELECT count(*) FROM snapshots WHERE path=?", (str(self.claude_file),)).fetchone()[0], 2)

    def test_deleted_source_is_kept_and_restorable(self):
        self.index()
        original = self.claude_file.read_bytes()
        self.claude_file.unlink()  # what the 30-day sweep does
        report = self.index()
        self.assertEqual(report["kept_after_source_deleted"], 1)
        self.assertTrue(self.jsonl("search", "login button"))
        listing = self.run_cli("sessions").stdout
        self.assertIn("[source deleted, kept here]", listing)
        dest = self.tmp / "restored dir" / "restored.jsonl"
        dest.parent.mkdir()
        out = self.run_cli("restore", CLAUDE_SESSION[:8], str(dest)).stdout
        self.assertIn("(verified)", out)
        self.assertEqual(dest.read_bytes(), original)
        again = self.run_cli("restore", CLAUDE_SESSION[:8], str(dest), check=False)
        self.assertNotEqual(again.returncode, 0)
        self.assertIn("never overwrites", again.stderr)
        self.assertEqual(dest.read_bytes(), original)

    def test_store_is_private(self):
        self.index()
        self.assertEqual(stat.S_IMODE(self.store.stat().st_mode), 0o700)
        self.assertEqual(stat.S_IMODE((self.store / "snapshots").stat().st_mode), 0o700)
        for f in [self.store / "history.sqlite", *(self.store / "snapshots").iterdir()]:
            self.assertEqual(stat.S_IMODE(f.stat().st_mode) & 0o077, 0, f"{f.name} is readable by others")

    def test_no_snapshots_option(self):
        self.index("--no-snapshots")
